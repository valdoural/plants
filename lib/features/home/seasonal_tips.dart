import 'package:flutter/material.dart';

class SeasonalTip {
  const SeasonalTip(this.month, this.icon, this.title, this.points);

  final String month;
  final IconData icon;
  final String title;
  final List<String> points;
}

/// Общие сезонные советы для комнатных растений (северное полушарие, средняя полоса).
SeasonalTip seasonalTip(DateTime date) {
  const months = [
    'январь', 'февраль', 'март', 'апрель', 'май', 'июнь',
    'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь',
  ];
  final m = months[date.month - 1];
  return switch (date.month) {
    12 || 1 || 2 => SeasonalTip(m, Icons.ac_unit, 'Зимний покой', const [
        'Поливайте реже: почва сохнет медленнее, а корни легко загнивают.',
        'Отопление сушит воздух — держите растения подальше от батарей.',
        'Подкормки до весны не нужны большинству растений.',
      ]),
    3 || 4 || 5 => SeasonalTip(m, Icons.spa, 'Весеннее пробуждение', const [
        'Лучшее время для пересадки — пока растение только начинает расти.',
        'Возобновите подкормки раз в 2–4 недели.',
        'Постепенно приучайте растения к яркому солнцу, чтобы не было ожогов.',
      ]),
    6 || 7 || 8 => SeasonalTip(m, Icons.wb_sunny, 'Летний рост', const [
        'В жару проверяйте почву чаще — полив может понадобиться через день.',
        'Притеняйте от полуденного солнца на южных окнах.',
        'Осматривайте листья снизу: летом активны паутинный клещ и тля.',
      ]),
    _ => SeasonalTip(m, Icons.eco, 'Подготовка к осени', const [
        'Сокращайте полив и подкормки по мере укорачивания дня.',
        'Занесите в дом балконные растения до первых заморозков.',
        'Протрите листья от пыли — им понадобится весь свет короткого дня.',
      ]),
  };
}
